from math import floor

from sympy import Rational
from symfem.functions import VectorFunction,MatrixFunction

from topoptlab.symbolic.cell import base_cell
from topoptlab.symbolic.parametric_map import jacobian
from topoptlab.symbolic.matrix_utils import simplify_matrix, generate_constMatrix
from topoptlab.symbolic.matrix_utils import eye,to_square,inverse

def jacobian_matrix(ndim: int,
                    nd_inds: list,
                    basis: list,
                    isoparam_kws: dict) -> MatrixFunction:
    """
    Create the matrix B_j to calculate the flattened Jacobian (C-order) j 
    of a vector field u. The Jacobian matrix is defined as

       J_ij = d u_i / d x_j
    
    and its "flattened" version is then 
       
       j = J.flatten() = B_j @ u.

    If one wants to get J just

       to_square(v=B_j@u, order="C")

    Parameters
    ----------
    ndim : int
        number of spatial dimensions.
    nd_inds : list
        node indices.
    basis : list
        list of basis functions as generated by base_cell.
    isoparam_kws : dictionary
        keywords for the isoparametric mapping.

    Returns
    -------
    B_j : symfem.functions.Matrixfunction
        jacobian matrix shape ( ndim**2 , n_nodes*ndim ).
    """
    #
    nrows = int(ndim**2)
    ncols = int(ndim * len(nd_inds))
    # compute gradients of basis functions
    Jinv = jacobian(ndim=ndim,
                    return_J=False, return_inv=True, return_det=False,
                    **isoparam_kws)
    gradN_T = (VectorFunction(basis).grad(ndim)@Jinv.transpose()).transpose()
    #
    b = [[0 for j in range(ncols)] for i in range(nrows)]
    for k in range(nrows):
        #
        b[k][floor(k/ndim)::ndim] = gradN_T[k%ndim]
    return MatrixFunction(b)

def small_strain_matrix(ndim: int,
                        nd_inds: list,
                        basis: list,
                        isoparam_kws: dict) -> MatrixFunction:
    """
    Create the small strain matrix to calculate engineering/infinitesimal 
    strains via
    
    eps = B_eps @ u
    
    where u are nodal displacements and eps_e a column vector of 
    length (ndim**2 + ndim)/2. This applies the engineering convention, i. e.
    the shear components are scaled by a factor of two compared to the small 
    strain tensor in matrix notation.

    Parameters
    ----------
    ndim : int
        number of spatial dimensions.
    nd_inds : list
        node indices.
    basis : list
        list of basis functions as generated by base_cell.
    isoparam_kws : dictionary
        keywords for the isoparametric mapping.

    Returns
    -------
    B_eps : symfem.functions.Matrixfunction
        small displacement matrix shape ( (ndim**2+ndim)/2 , n_nodes*ndim ).
    """
    #
    nrows = int((ndim**2 + ndim) /2)
    ncols = int(ndim * len(nd_inds))
    # compute gradients of basis functions
    Jinv = jacobian(ndim=ndim,
                    return_J=False, return_inv=True, return_det=False,
                    **isoparam_kws)
    gradN_T = (VectorFunction(basis).grad(ndim)@Jinv.transpose()).transpose()
    #
    b = [[0 for j in range(ncols)] for i in range(nrows)]
    # tension
    for i in range(ndim):
        b[i][i::ndim] = gradN_T[i]
    # shear
    i,j = ndim-2,ndim-1
    for k in range(nrows-ndim):
        #
        b[ndim+k][i::ndim] = gradN_T[j]
        b[ndim+k][j::ndim] = gradN_T[i]
        #
        i,j = (i+1)%ndim , (j+1)%ndim
    return MatrixFunction(b)

def eng_strain(ndim: int,
               element_type: str= "Lagrange",
               order: int = 1) -> MatrixFunction:
    """
    Symbolically compute engineering strain in engineering convention, i. e.
    the shear components are scaled by a factor of two compared to the small 
    strain tensor in matrix notation.

    Parameters
    ----------
    ndim : int
        number of spatial dimensions. Must be between 1 and 3.
    element_type : str
        type of element.
    order : int
        order of element.

    Returns
    -------
    eng_strains : MatrixFunction
        engineering strains in Voigt notation shape ( (ndim**2 + ndim)/2 ) .

    """
    #
    vertices, nd_inds, ref, basis  = base_cell(ndim=ndim,
                                               element_type=element_type,
                                               order=order)
    # small strain matrix
    b = small_strain_matrix(ndim=ndim,
                            nd_inds=nd_inds,
                            basis=basis,
                            isoparam_kws={"element_type": element_type,
                                          "order": order})
    # nodal displacements
    u = generate_constMatrix(1,b.shape[1], "u")
    return simplify_matrix( b@u )

def dispgrad_matrix(ndim: int, 
                    nd_inds: list,
                    basis: list,
                    isoparam_kws: dict) -> MatrixFunction:
    """
    Create the matrix to calculate the flattened displacement gradient via
    
    h = B_h @ u
    
    where u are nodal displacements and h a column vector of length ndim**2. 
    You recover the full deformation gradient by 
    
    H = h.reshape(ndim,ndim).

    Parameters
    ----------
    ndim : int
        number of spatial dimensions.
    nd_inds : list
        node indices.
    basis : list
        list of basis functions as generated by base_cell.
    isoparam_kws : dictionary
        keywords for the isoparametric mapping.

    Returns
    -------
    B_h : symfem.functions.Matrixfunction
        matrix to calculate flattened displacement gradient shape 
        (ndim**2 , n_nodes*ndim).
    """
    # compute gradients of basis functions
    Jinv = jacobian(ndim=ndim,
                    return_J=False, return_inv=True, return_det=False,
                    **isoparam_kws)
    gradN_T = (VectorFunction(basis).grad(ndim)@Jinv.transpose()).transpose()
    #
    dispgrad_matrix = [[0 for j in range(int(ndim * len(nd_inds)))] \
                        for i in range(int(ndim**2))]
    # 
    for i in range(ndim):
        for j in range(ndim): 
            dispgrad_matrix[i*ndim + j][i::ndim] = gradN_T[j]
    return MatrixFunction(dispgrad_matrix)

def disp_grad(ndim: int,
              u: None | MatrixFunction = None,
              element_type: str = "Lagrange",
              order: int = 1,
              shape: str = "square") -> MatrixFunction:
    """
    Symbolically compute the displacement gradient. If the shape argument is 
    "square", compute 
        
    H_ij = d u_i / d x_j.
    
    If the shape argument is "voigt", flatten H to a (ndim**2,1) Matrixfunction.

    Parameters
    ----------
    ndim : int
        number of spatial dimensions. Must be between 1 and 3.
    u : None or MatrixFunction
        nodal displacements.
    element_type : str
        type of element.
    order : int
        order of element.
    shape : str
        indicate output shape either as a Voigt vector ("voigt") or a square 
        matrix ("square").

    Returns
    -------
    H : symfem.MatrixFunction
        symbolic displacement gradient of shape (ndim,ndim) or (ndim**2,1).

    """
    #
    vertices, nd_inds, ref, basis  = base_cell(ndim=ndim,
                                               element_type=element_type,
                                               order=order)
    # small strain matrix
    b = dispgrad_matrix(ndim=ndim,
                        nd_inds=nd_inds,
                        basis=basis,
                        isoparam_kws={"element_type": element_type,
                                      "order": order})
    # nodal displacements
    if u is None:
        u = generate_constMatrix(ncol=1, nrow=b.shape[1], name="u")
    #
    h=simplify_matrix(M=b@u)
    if shape=="square":
        return to_square(v=h, order="C")
    elif shape=="voigt":
        return h
    else:
        raise ValueError("shape can only be one of the followings options: ",
                         "square, voigt")

def def_grad(ndim: int,
             u: None | MatrixFunction = None,
             element_type: str = "Lagrange",
             order: int = 1,
             shape: str = "square"):
    """
    Symbolically compute deformation gradient. If the shape argument is 
    "square", compute 
    
    F_ij = delta_ij + d u_i / d x_j
    
    If the shape argument is "voigt", flatten H to a (ndim**2,1) Matrixfunction.

    Parameters
    ----------
    ndim : int
        number of spatial dimensions. Must be between 1 and 3.
    u : None or MatrixFunction
        nodal displacements.
    element_type : str
        type of element.
    order : int
        order of element.
    shape : str
        indicate output shape either as a Voigt vector ("voigt") or a square 
        matrix ("square").

    Returns
    -------
    F : symfem.MatrixFunction
        symbolic deformation gradient of shape (ndim,ndim) or (ndim**2,1).

    """
    #
    I = eye(size=ndim)
    if shape=="square":
        pass
    elif shape=="voigt":
        I = MatrixFunction([[I[i%ndim, floor(i/ndim)]] for i in range(ndim**2) ])
    else:
        raise ValueError("shape can only be one of the followings options: ",
                         "square, voigt")
    #
    H = disp_grad(ndim=ndim,
                  u=u,
                  element_type=element_type,
                  order=order,
                  shape=shape)
    return I + H

def _as_square_defgrad(F: None | MatrixFunction,
                       ndim: int,
                       element_type: str = "Lagrange",
                       order: int = 1) -> MatrixFunction:
    """
    Return the deformation gradient F in matrix form of shape (ndim,ndim). If
    F is None, it is calculated symbolically via def_grad. If F is flattened
    of shape (ndim**2,1), it is reshaped in C-order consistent with
    dispgrad_matrix and def_grad(shape="voigt"), i. e. F.flatten()[i*ndim+j]
    = F_ij.

    Parameters
    ----------
    F : None or symfem.functions.MatrixFunction
        symbolic deformation gradient of shape (ndim,ndim) or (ndim**2,1).
    ndim : int
        number of spatial dimensions. Only used if F is None.
    element_type : str
        type of element. Only used if F is None.
    order : int
        order of element. Only used if F is None.

    Returns
    -------
    F : symfem.functions.MatrixFunction
        symbolic deformation gradient of shape (ndim,ndim).
    """
    if F is None:
        return def_grad(ndim=ndim,
                        element_type=element_type,
                        order=order,
                        shape="square")
    elif F.shape[1] == 1 and F.shape[0] > 1:
        return to_square(v=F, order="C")
    elif F.shape[0] == F.shape[1]:
        return F
    else:
        raise ValueError("F must be of shape (ndim,ndim) or (ndim**2,1): ",
                         F.shape)

def cauchy_strain(ndim: int,
                  F: None | MatrixFunction = None,
                  element_type: str = "Lagrange",
                  order: int = 1) ->  MatrixFunction:
    """
    Symbolically compute right Cauchy–Green deformation tensor:
        
        C = F.T @ F
        
    where F is the deformation gradient.

    Parameters
    ----------
    ndim : int
        number of spatial dimensions. Must be between 1 and 3.
    F : None or symfem.functions.MatrixFunction
        symbolic deformation gradient of shape (ndim,ndim) or flattened in 
        C-order of shape (ndim**2,1). If not None, then all the other 
        arguments are ignored and the strain is calculated with the provided 
        F. If None, F is calculated via def_grad.
    element_type : str
        type of element.
    order : int
        order of element.

    Returns
    -------
    C : symfem.MatrixFunction
        symbolic right Cauchy–Green deformation tensor of shape (ndim,ndim) 

    """
    #
    F = _as_square_defgrad(F=F, ndim=ndim,
                           element_type=element_type, order=order)
    return simplify_matrix(F.transpose()@F)

def lagrangian_strain(ndim: int,
                      F: None | MatrixFunction = None,
                      element_type: str = "Lagrange",
                      order: int = 1) ->  MatrixFunction:
    """
    Symbolically compute Green-Lagrangian strain tensor:
        
        E = 1/2 * ( C - I )
    
    I is the identity matrix and C the Cauchy–Green deformation tensor.

    Parameters
    ----------
    ndim : int
        number of spatial dimensions. Must be between 1 and 3.
    F : None or symfem.functions.MatrixFunction
        symbolic deformation gradient of shape (ndim,ndim) or flattened in 
        C-order of shape (ndim**2,1). If not None, then all the other 
        arguments are ignored and the strain is calculated with the provided 
        F. If None, F is calculated via def_grad.
    element_type : str
        type of element.
    order : int
        order of element.

    Returns
    -------
    E : symfem.MatrixFunction
        symbolic Green-Lagrangian strain tensor of shape (ndim,ndim) 

    """
    #
    F = _as_square_defgrad(F=F, ndim=ndim,
                           element_type=element_type, order=order)
    return (cauchy_strain(ndim=F.shape[0],
                          F=F)-eye(F.shape[0])).__mul__(Rational(1,2))

def lagrangian_strainvar_matrix(ndim : int,
                                nd_inds : list,
                                basis: list,
                                F : None | MatrixFunction,
                                isoparam_kws: dict) ->  MatrixFunction:
    """
    Symbolically compute the variation of the Green-Lagrangian strain tensor 
    delta E around the current displacement u0 and deformation gradient F0:
        
        delta E = 1/2 * (F0.T @ grad(u) + grad(u) @ F0).
    
    Return the matrix B_dE to calculate the flattened variation of the 
    Lagrangian strain E in Voigt notation from nodal displacements u:
            
        flattened(var(E)) = B_dE(F)@u
        
    The Lagrangian strain reads as: 
        
        E = 1/2 * ( C - I )
    
    I is the identity matrix and C the Cauchy–Green deformation tensor:
        
        C = F.T @ F
        
    where F is the deformation gradient in matrix notation.
    
    Parameters
    ----------
    ndim : int
        number of spatial dimensions.
    nd_inds : list
        node indices.
    basis : list
        list of basis functions as generated by base_cell.
    F : symfem.functions.MatrixFunction
        symbolic deformation gradient of shape (ndim,ndim). 
    isoparam_kws : dictionary
        keywords for the isoparametric mapping.

    Returns
    -------
    B_dE : symfem.functions.Matrixfunction
        matrix for variation of Green-Lagrange strain  
        ((ndim**2+ndim)/2 , n_nodes*ndim ).

    """
    #
    nrows = int((ndim**2 + ndim) /2)
    ncols = int(ndim * len(nd_inds))
    #
    if F is None:
        F = generate_constMatrix(ncol=ndim, nrow=ndim, name="F")
    # compute gradients of basis functions
    Jinv = jacobian(ndim=ndim,
                    return_J=False, return_inv=True, return_det=False,
                    **isoparam_kws)
    gradN_T = (VectorFunction(basis).grad(ndim)@Jinv.transpose()).transpose()
    #
    b = [[0 for j in range(ncols)] for i in range(nrows)]
    # tension
    for i in range(ndim): # row
        for j in range(ndim): # col
            b[i][j::ndim] = gradN_T[i].__mul__(F[j,i])
            #print(b,"\n")
    # shear
    if ndim==2:
        inds=[[0],[1]]
    elif ndim==3:
        inds=[[1,0,0],[2,2,1]]
    for i in range(nrows-ndim): # row
        for j in range(ndim): # col
            b[ndim+i][j::ndim] = gradN_T[inds[0][i]].__mul__(F[j,inds[1][i]]) +\
                                 gradN_T[inds[1][i]].__mul__(F[j,inds[0][i]])
    return MatrixFunction(b)

def lagrangian_strainvar(ndim: int,
                         F: None | MatrixFunction = None,
                         element_type: str = "Lagrange",
                         order: int = 1) ->  MatrixFunction:
    """
    Symbolically compute the variation of the Green-Lagrangian strain tensor 
    delta E around the current displacement u0 and deformation gradient F0:
        
        delta E = 1/2 * (F0.T @ grad(u) + grad(u).T @ F0)
    
    where grad(u) is the gradient of the displacement variation interpolated 
    from the nodal values u (symbols u1, u2, ...). In Voigt notation with 
    engineering convention this equals lagrangian_strainvar_matrix(F0) @ u.
    
    Parameters
    ----------
    ndim : int
        number of spatial dimensions. Must be between 1 and 3.
    F : None or symfem.functions.MatrixFunction
        symbolic deformation gradient F0 of shape (ndim,ndim) or flattened in
        C-order of shape (ndim**2,1). If None, F0 is generated from the 
        constant symbols F11, F12, ... (independent of the nodal 
        displacement variation u).
    element_type : str
        type of element.
    order : int
        order of element.

    Returns
    -------
    dE : symfem.MatrixFunction
        symbolic variation of the Green-Lagrangian strain tensor of shape 
        (ndim,ndim)

    """
    # F0 must not share the symbols of the displacement variation
    if F is None:
        F = generate_constMatrix(ncol=ndim, nrow=ndim, name="F")
    F = _as_square_defgrad(F=F, ndim=ndim,
                           element_type=element_type, order=order)
    # gradient of the displacement variation (nodal values u)
    dH = disp_grad(ndim=F.shape[0],
                   u=None,
                   element_type=element_type,
                   order=order,
                   shape="square")
    return simplify_matrix((F.transpose()@dH + dH.transpose()@F)\
                           .__mul__(Rational(1,2)))

def finger_strain(ndim: int,
                  F: None | MatrixFunction = None,
                  element_type: str = "Lagrange",
                  order: int = 1) ->  MatrixFunction:
    """
    Symbolically compute the inverse of the right Cauchy–Green deformation 
    tensor C:
        
        inv(C) = inv(F.T @ F)
    
    Note: inv(C) is also known as Piola deformation tensor. In parts of the 
    literature the Finger tensor denotes the left Cauchy–Green tensor B 
    instead (see green_strain). Name kept consistent with 
    topoptlab.elements.strain_measures.finger_strain.

    Parameters
    ----------
    ndim : int
        number of spatial dimensions. Must be between 1 and 3.
    F : None or symfem.functions.MatrixFunction
        symbolic deformation gradient of shape (ndim,ndim) or flattened in 
        C-order of shape (ndim**2,1). If not None, then all the other 
        arguments are ignored and the strain is calculated with the provided 
        F. If None, F is calculated via def_grad.
    element_type : str
        type of element.
    order : int
        order of element.

    Returns
    -------
    Finger : symfem.MatrixFunction
        symbolic inverse of right Cauchy–Green tensor of shape (ndim,ndim) 

    """
    #
    F = _as_square_defgrad(F=F, ndim=ndim,
                           element_type=element_type, order=order)
    C = cauchy_strain(ndim=F.shape[0],
                      F=F)
    return simplify_matrix( inverse(C) )

def green_strain(ndim: int,
                 F: None | MatrixFunction = None,
                 element_type: str = "Lagrange",
                 order: int = 1) ->  MatrixFunction:
    """
    Symbolically compute the left Cauchy–Green deformation tensor B:
    
        B = F @ F.T
    
    Note: despite the function name, this is NOT the Green-Lagrangian strain 
    E (see lagrangian_strain).

    Parameters
    ----------
    ndim : int
        number of spatial dimensions. Must be between 1 and 3.
    F : None or symfem.functions.MatrixFunction
        symbolic deformation gradient of shape (ndim,ndim) or flattened in 
        C-order of shape (ndim**2,1). If not None, then all the other 
        arguments are ignored and the strain is calculated with the provided 
        F. If None, F is calculated via def_grad.
    element_type : str
        type of element.
    order : int
        order of element.

    Returns
    -------
    B : symfem.MatrixFunction
        symbolic left Cauchy–Green deformation tensor of shape (ndim,ndim) 

    """
    #
    F = _as_square_defgrad(F=F, ndim=ndim,
                           element_type=element_type, order=order)
    return simplify_matrix(F@F.transpose())
